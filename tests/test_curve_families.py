"""Tests for the closed-form price-curve families."""

from __future__ import annotations

import numpy as np
import pytest

from fleet_sim.prices.curves import (
    Cubic,
    CubicFit,
    CubicOffset,
    CubicOffsetFit,
    SignedQuadratic,
    SignedQuadraticFit,
)

_Family = Cubic | SignedQuadratic | CubicOffset
_Fit = CubicFit | SignedQuadraticFit | CubicOffsetFit

# Each case: a family, the fit holding the true parameters, and the
# residual-load range (GW) to draw synthetic data from.
_CASES: list[tuple[_Family, _Fit, tuple[float, float]]] = [
    (Cubic(), CubicFit(a=0.004), (5.0, 40.0)),
    (SignedQuadratic(), SignedQuadraticFit(a=0.12), (-10.0, 40.0)),
    (CubicOffset(), CubicOffsetFit(a0=30.0, a1=1.5, a3=0.003), (-10.0, 40.0)),
]


def test_cubic_hand_worked() -> None:
    """Cubic fit on two points, by hand.

    R = [1, 2], y = [2, 16].
    â = Σ yR³ / Σ R⁶ = (2·1 + 16·8) / (1 + 64) = 130 / 65 = 2.
    predict(3) = 2·27 = 54.  slope(3) = 3·2·9 = 54.
    """
    fitted = Cubic().fit([1.0, 2.0], [2.0, 16.0])
    assert fitted.a == pytest.approx(2.0)
    assert fitted.predict(3.0) == pytest.approx(54.0)
    assert fitted.slope(3.0) == pytest.approx(54.0)


@pytest.mark.parametrize(("family", "truth", "r_range"), _CASES)
def test_family_recovers_known_parameters(
    family: _Family, truth: _Fit, r_range: tuple[float, float]
) -> None:
    """Fitting noisy data generated by a family's own formula recovers it."""
    rng = np.random.default_rng(seed=70)
    r = rng.uniform(*r_range, size=2000)
    y = np.array([truth.predict(float(x)) for x in r]) + rng.normal(0.0, 2.0, r.size)

    fitted = family.fit(r.tolist(), y.tolist())

    expected = truth.model_dump()
    actual = fitted.model_dump()
    assert actual.keys() == expected.keys()
    for name, value in expected.items():
        assert actual[name] == pytest.approx(value, rel=0.05), name


@pytest.mark.parametrize(("_family", "fitted", "_r_range"), _CASES)
@pytest.mark.parametrize("r_gw", [-7.5, 0.5, 22.0])
def test_slope_matches_finite_difference(
    _family: _Family,
    fitted: _Fit,
    _r_range: tuple[float, float],
    r_gw: float,
) -> None:
    """Analytic slope agrees with a central difference of predict."""
    h = 1e-4
    numeric = (fitted.predict(r_gw + h) - fitted.predict(r_gw - h)) / (2 * h)
    assert fitted.slope(r_gw) == pytest.approx(numeric, rel=1e-6)


@pytest.mark.parametrize(
    ("family", "r_gw", "y", "message"),
    [
        (Cubic(), [], [], "no observations"),
        (Cubic(), [1.0, 2.0], [1.0], "same length"),
        (Cubic(), [0.0, 0.0], [1.0, 2.0], "every r_gw is zero"),
        (SignedQuadratic(), [0.0], [1.0], "every r_gw is zero"),
        (CubicOffset(), [1.0, 1.0, 2.0], [1.0, 2.0, 3.0], "3 distinct"),
    ],
)
def test_fit_rejects_invalid_data(
    family: _Family, r_gw: list[float], y: list[float], message: str
) -> None:
    with pytest.raises(ValueError, match=message):
        family.fit(r_gw, y)
